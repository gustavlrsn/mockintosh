export default defineApp({
  id: "myapp",
  title: "My App",
  icon: "myapp/icon",
  defaultSize: { width: 200, height: 120 },
  Component() {
    const app = useApp();
    const [n, setN] = createSignal(0);

    // Menus close over this window's state; the effect keeps them in sync.
    createEffect(() => {
      app.setMenus([
        {
          label: "File",
          items: [
            { label: "Reset", shortcut: "R", disabled: n() === 0, onClick: () => setN(0) },
          ],
        },
      ]);
    });

    return (
      <box padding={8} flexDirection="column" gap={8} background={0}>
        <text font="menu">{`Clicks: ${n()}`}</text>
        <Button label="Click" onClick={() => setN((v) => v + 1)} />
      </box>
    );
  },
});
